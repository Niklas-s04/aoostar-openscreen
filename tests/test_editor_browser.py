"""Real browser coverage for canvas drafts, persistence, guards and media."""
import io
import os
from PIL import Image
from playwright.sync_api import sync_playwright, expect
from test_browser import demo_server


def test_editor_drafts_interactions_and_media(demo_server):
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path=os.getenv('PLAYWRIGHT_EXECUTABLE_PATH'))
        page = browser.new_page(viewport={'width': 1500, 'height': 1100})
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(demo_server + '/#display')
        expect(page.locator('#editor-preview')).to_be_visible()
        expect(page.locator('#editor-preview-status')).to_contain_text('Entwurfsvorschau')
        assert page.locator('[data-edit-page]').count() == 1
        page.get_by_label('Elementtyp').select_option('text')
        page.get_by_role('button', name='Element hinzufügen', exact=True).click()
        page.get_by_label('Text', exact=True).fill('Mein Display')
        page.get_by_label('X', exact=True).fill('100')
        page.get_by_label('Y', exact=True).fill('80')
        expect(page.locator('#editor-dirty')).to_have_text('Ungespeichert')
        bound = page.locator('.element-bound.selected')
        box = bound.bounding_box()
        page.mouse.move(box['x'] + box['width']/2, box['y'] + box['height']/2)
        page.mouse.down()
        page.mouse.move(box['x'] + box['width']/2 + 30, box['y'] + box['height']/2 + 15, steps=4)
        page.mouse.up()
        assert int(page.get_by_label('X', exact=True).input_value()) > 100
        page.get_by_role('button', name='Rückgängig', exact=True).click()
        expect(page.get_by_label('X', exact=True)).to_have_value('100')
        page.get_by_role('button', name='Wiederholen', exact=True).click()
        assert int(page.get_by_label('X', exact=True).input_value()) > 100
        page.locator('#editor-canvas').focus()
        x = int(page.get_by_label('X', exact=True).input_value())
        page.keyboard.press('Shift+ArrowRight')
        expect(page.get_by_label('X', exact=True)).to_have_value(str(x+10))
        handle = page.locator('.resize-handle').bounding_box()
        width = int(page.get_by_label('Breite', exact=True).input_value())
        page.mouse.move(handle['x']+7, handle['y']+7)
        page.mouse.down()
        page.mouse.move(handle['x']+27, handle['y']+17, steps=3)
        page.mouse.up()
        assert int(page.get_by_label('Breite', exact=True).input_value()) > width
        page.get_by_role('button', name='Duplizieren', exact=True).click()
        expect(page.locator('.layer')).to_have_count(5)
        page.get_by_role('button', name='Löschen', exact=True).click()
        expect(page.locator('.layer')).to_have_count(4)
        page.get_by_role('button', name='Mein Display Text').click()
        layer = page.locator('.layer.selected')
        layer.get_by_role('button', name='Sperren', exact=True).click()
        expect(page.locator('.element-bound.selected')).to_have_class('element-bound selected locked')
        page.locator('#editor-canvas').focus()
        locked_x = page.get_by_label('X', exact=True).input_value()
        page.keyboard.press('ArrowRight')
        expect(page.get_by_label('X', exact=True)).to_have_value(locked_x)
        page.locator('.layer.selected').get_by_role('button', name='Entsperren', exact=True).click()
        page.locator('.layer.selected').get_by_role('button', name='Ausblenden', exact=True).click()
        expect(page.locator('.element-bound.selected')).to_have_count(0)
        page.locator('.layer.selected').get_by_role('button', name='Einblenden', exact=True).click()
        page.get_by_role('button', name='Änderungen speichern', exact=True).click()
        expect(page.locator('#editor-dirty')).to_have_text('Gespeichert')
        page.reload()
        page.get_by_role('button', name='Mein Display Text').click()
        expect(page.get_by_label('Text', exact=True)).to_have_value('Mein Display')
        page.get_by_label('Text', exact=True).fill('Verwerfen')
        page.once('dialog', lambda dialog: dialog.dismiss())
        page.get_by_role('link', name='Datenquellen', exact=True).click()
        expect(page.get_by_label('Text', exact=True)).to_have_value('Verwerfen')
        page.once('dialog', lambda dialog: dialog.accept())
        page.get_by_role('button', name='Verwerfen', exact=True).click()
        page.get_by_role('button', name='Mein Display Text').click()
        expect(page.get_by_label('Text', exact=True)).to_have_value('Mein Display')
        page.get_by_role('button', name='Seite hinzufügen', exact=True).click()
        expect(page.locator('[data-edit-page]')).to_have_count(2)
        page.get_by_label('Seitenname', exact=True).fill('Zweite Seite')
        page.get_by_role('button', name='Änderungen speichern', exact=True).click()
        expect(page.locator('#editor-dirty')).to_have_text('Gespeichert')
        page.get_by_label('Vorlage', exact=True).select_option('clock')
        page.get_by_role('button', name='Vorlage anwenden', exact=True).click()
        expect(page.locator('.layer')).to_have_count(2)
        page.get_by_label('Vorlage', exact=True).select_option('blank')
        page.once('dialog', lambda dialog: dialog.dismiss())
        page.get_by_role('button', name='Vorlage anwenden', exact=True).click()
        expect(page.locator('.layer')).to_have_count(2)
        page.once('dialog', lambda dialog: dialog.accept())
        page.get_by_role('button', name='Verwerfen', exact=True).click()
        page.locator('.media-library summary').click()
        image = io.BytesIO()
        Image.new('RGB', (40, 30), '#ff8800').save(image, format='PNG')
        page.locator('#asset-upload').set_input_files({'name':'orange.png','mimeType':'image/png','buffer':image.getvalue()})
        expect(page.locator('#notice')).to_have_text('Medium hochgeladen')
        page.locator('.media-library summary').click()
        page.get_by_role('button', name='Einfügen', exact=True).click()
        expect(page.get_by_label('Medium', exact=True)).not_to_have_value('')
        page.locator('.media-library summary').click()
        page.locator('#asset-upload').set_input_files({'name':'bad.png','mimeType':'image/png','buffer':b'not an image'})
        expect(page.locator('#notice')).not_to_have_text('Medium hochgeladen')
        page.get_by_role('button', name='Änderungen speichern', exact=True).click()
        expect(page.locator('#editor-dirty')).to_have_text('Gespeichert')
        page.set_viewport_size({'width':390,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        expect(page.get_by_role('button', name='Änderungen speichern', exact=True)).to_be_visible()
        assert not errors
        browser.close()

def test_custom_canvas_and_network_player(demo_server, tmp_path):
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path=os.getenv('PLAYWRIGHT_EXECUTABLE_PATH'))
        page=browser.new_page(viewport={'width':1600,'height':1000})
        errors=[]
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.goto(demo_server+'/#display')
        page.get_by_label('Seitenbreite',exact=True).fill('800')
        page.get_by_label('Seitenhöhe',exact=True).fill('480')
        page.get_by_role('button',name='Seitengröße anwenden',exact=True).click()
        page.get_by_role('button',name='Änderungen speichern',exact=True).click()
        expect(page.locator('#editor-dirty')).to_have_text('Gespeichert')
        expect(page.locator('#editor-preview')).to_have_js_property('naturalWidth',800)
        page.get_by_role('link',name='Einstellungen',exact=True).click()
        page.get_by_label('Ausgabetyp',exact=True).select_option('browser')
        page.get_by_label('Ausgabebreite',exact=True).fill('1280')
        page.get_by_label('Ausgabehöhe',exact=True).fill('720')
        page.get_by_role('button',name='Einstellungen speichern',exact=True).click()
        expect(page.get_by_role('button',name='Einstellungen speichern',exact=True)).to_be_enabled()
        expect(page.locator('#notice')).to_have_text('Änderungen gespeichert')
        page.get_by_role('link',name='Display',exact=True).click()
        expect(page.get_by_label('Seitenbreite',exact=True)).to_have_value('800')
        expect(page.locator('#editor-dirty')).to_have_text('Gespeichert')
        page.screenshot(path=str(tmp_path/'editor-custom.png'),full_page=True)
        player=browser.new_page()
        player.on('pageerror',lambda error:errors.append(str(error)))
        player.goto(demo_server+'/display')
        expect(player.locator('#output')).to_have_js_property('naturalWidth',1280)
        assert player.locator('#output').evaluate('(img)=>img.naturalHeight')==720
        expect(player.get_by_role('button',name='Vollbild',exact=True)).to_be_visible()
        page.get_by_role('link',name='Einstellungen',exact=True).click()
        page.get_by_role('button',name='Displays suchen',exact=True).click()
        expect(page.locator('#discovery-note')).to_contain_text('1 Browser-Player')
        choices=page.get_by_label('Browser-Player als Größenreferenz',exact=True)
        choices.select_option(index=1)
        page.get_by_role('button',name='Ausgabe prüfen / Größe erkennen',exact=True).click()
        expect(page.locator('#probe-result')).to_contain_text('Browsergröße gemeldet')
        reported=player.evaluate('Math.round(screen.width*devicePixelRatio)')
        expect(page.get_by_label('Ausgabebreite',exact=True)).to_have_value(str(reported))
        page.get_by_role('button',name='Einstellungen speichern',exact=True).click()
        expect(page.get_by_role('button',name='Einstellungen speichern',exact=True)).to_be_enabled()
        expect(page.locator('#notice')).to_have_text('Änderungen gespeichert')
        page.get_by_label('Gemeldete Größe beim Speichern übernehmen',exact=True).uncheck()
        page.get_by_label('Ausgabebreite',exact=True).fill('800')
        page.get_by_role('button',name='Einstellungen speichern',exact=True).click()
        expect(page.get_by_role('button',name='Einstellungen speichern',exact=True)).to_be_enabled()
        expect(page.locator('#notice')).to_have_text('Änderungen gespeichert')
        page.reload()
        expect(page.get_by_label('Ausgabebreite',exact=True)).to_have_value('800')
        expect(page.get_by_label('Serielles Gerät',exact=True)).to_have_attribute('list','display-devices')
        assert not errors
        browser.close()
